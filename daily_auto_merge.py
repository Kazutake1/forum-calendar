#!/usr/bin/env python3
"""Fail-closed automatic daily-event PR merge after the exact GitHub CI run passes.

Trusted main-only scheduled workflow invokes this script after its GitHub App
creates a PR.  It only merges a PR generated by the dedicated App bot with an
exact two-file allowlist, matching local bytes, unchanged main, and a completed
successful 'Calendar Integrity Tests' pull_request run at the exact head SHA.
No retries on a failed check; no secret values or source data are logged.
"""
import base64
import binascii
from datetime import datetime, timedelta, timezone
import re
import json
import os
from pathlib import Path
import subprocess
import sys
import time
from urllib.parse import quote

REPO = "Kazutake1/forum-calendar"
BOT = "forum-calendar-event-writer[bot]"
WORKFLOW = ".github/workflows/test-integrity.yml"
ALLOWED = frozenset(("events.json", "update-meta.json"))
WAIT_SECONDS = 11 * 60
POLL_SECONDS = 12
PAGES_WORKFLOW = "dynamic/pages/pages-build-deployment"
PAGES_WAIT_SECONDS = 9 * 60


class UnsafeToPublish(RuntimeError):
    pass


def api(endpoint, *, read_actions=False, method=None, fields=()):
    env = dict(os.environ)
    if read_actions:
        env["GH_TOKEN"] = env["GH_CI_READ_TOKEN"]
    cmd = ["gh", "api", endpoint]
    if method:
        cmd.extend(("-X", method))
    for field in fields:
        cmd.extend(("-f", field))
    result = subprocess.run(cmd, env=env, text=True, capture_output=True,
                            check=False, timeout=40)
    if result.returncode:
        raise UnsafeToPublish("GitHub API request failed; no automatic publication")
    try:
        return json.loads(result.stdout)
    except (ValueError, TypeError) as exc:
        raise UnsafeToPublish("Invalid GitHub API response; refusing publication") from exc


def expected_environment():
    repo = os.environ.get("REPOSITORY", "")
    base = os.environ.get("BASE_SHA", "")
    branch = os.environ.get("PR_BRANCH", "")
    pr_number = os.environ.get("PR_NUMBER", "")
    if repo != REPO or len(base) != 40 or any(c not in "0123456789abcdef" for c in base):
        raise UnsafeToPublish("Unexpected repository or original main SHA")
    if (not branch.startswith("automation/daily-events/")
            or len(branch.split("/")) != 3
            or not all(x.isdigit() for x in branch.split("/")[-1].split("-"))
            or len(branch.split("/")[-1].split("-")) != 2):
        raise UnsafeToPublish("Unexpected daily update branch")
    if not pr_number.isdecimal() or int(pr_number) < 1:
        raise UnsafeToPublish("Invalid daily update PR number")
    if not os.environ.get("GH_TOKEN") or not os.environ.get("GH_CI_READ_TOKEN"):
        raise UnsafeToPublish("Required GitHub credentials are unavailable")
    return base, branch, int(pr_number)


def current_main():
    data = api(f"repos/{REPO}/git/ref/heads/main")
    return data["object"]["sha"]


def inspect_pr(base_sha, branch, number):
    pr = api(f"repos/{REPO}/pulls/{number}")
    head = pr.get("head") or {}
    base = pr.get("base") or {}
    author = pr.get("user") or {}
    if not (pr.get("number") == number and pr.get("state") == "open"
            and not pr.get("draft") and not pr.get("merged")
            and author.get("login") == BOT
            and head.get("ref") == branch
            and (head.get("repo") or {}).get("full_name") == REPO
            and base.get("ref") == "main" and base.get("sha") == base_sha):
        raise UnsafeToPublish("PR metadata, source or base does not meet publication policy")
    head_sha = head.get("sha", "")
    if len(head_sha) != 40 or any(c not in "0123456789abcdef" for c in head_sha):
        raise UnsafeToPublish("Invalid PR head SHA")

    changes = api(f"repos/{REPO}/pulls/{number}/files?per_page=100")
    if not isinstance(changes, list) or not 1 <= len(changes) <= 2:
        raise UnsafeToPublish("Invalid daily PR file count")
    paths = {item.get("filename") for item in changes}
    if len(paths) != len(changes) or not paths.issubset(ALLOWED):
        raise UnsafeToPublish("Unexpected file in daily PR")
    if any(item.get("status") != "modified" for item in changes):
        raise UnsafeToPublish("A daily PR added, removed or renamed an unexpected file")
    for path in paths:
        remote = api(f"repos/{REPO}/contents/{path}?ref={quote(branch, safe='')}")
        if remote.get("type") != "file" or remote.get("encoding") != "base64":
            raise UnsafeToPublish("Unexpected remote event-data encoding")
        try:
            contents = base64.b64decode(remote["content"], validate=False)
        except (ValueError, KeyError) as exc:
            raise UnsafeToPublish("Unusable remote event-data payload") from exc
        if contents != Path(path).read_bytes():
            raise UnsafeToPublish("Remote PR payload differs from locally checked data")
    return head_sha


def ci_status(branch, head_sha, number):
    # Use the ordinary read-only Actions token, not the App's Contents/PR token.
    data = api(
        f"repos/{REPO}/actions/workflows/test-integrity.yml/runs?"
        f"event=pull_request&head_sha={head_sha}&per_page=100",
        read_actions=True)
    matches = []
    for item in data.get("workflow_runs", []):
        prs = item.get("pull_requests") or []
        if (item.get("event") == "pull_request"
                and item.get("head_sha") == head_sha
                and item.get("head_branch") == branch
                and item.get("path", "").split("@", 1)[0] == WORKFLOW
                and (item.get("actor") or {}).get("login") == BOT
                and any(pr.get("number") == number
                        and (pr.get("head") or {}).get("sha") == head_sha
                        for pr in prs)):
            matches.append(item)
    if len(matches) > 1:
        raise UnsafeToPublish("Ambiguous CI runs for PR head")
    if not matches:
        return "pending"
    run = matches[0]
    if run.get("status") != "completed":
        return "pending"
    if run.get("conclusion") != "success":
        raise UnsafeToPublish("Required CI did not pass; refusing publication")
    return "success"



def cleanup_stale_daily_prs():
    """Close only an old, verifiably App-owned daily PR; never merge stale data.

    The scheduled job times out after 35 minutes. A two-hour age limit avoids
    touching a PR from a still-active or recently interrupted update. Any
    unknown daily-looking PR halts the new run rather than being modified.
    """
    base_sha = os.environ.get("BASE_SHA", "")
    if (os.environ.get("REPOSITORY") != REPO or
            not re.fullmatch(r"[0-9a-f]{40}", base_sha) or
            not os.environ.get("GH_TOKEN")):
        raise UnsafeToPublish("Invalid cleanup repository, base SHA or App credentials")
    if current_main() != base_sha:
        raise UnsafeToPublish("main changed before stale PR cleanup")

    opened = api(f"repos/{REPO}/pulls?state=open&base=main&per_page=100")
    if not isinstance(opened, list) or len(opened) >= 100:
        raise UnsafeToPublish("Cannot fully inspect open PR list")
    candidates = [
        item for item in opened
        if str((item.get("head") or {}).get("ref", "")).startswith(
            "automation/daily-events/")
    ]
    if not candidates:
        return
    if len(candidates) != 1:
        raise UnsafeToPublish("Multiple old daily PRs; no automatic cleanup")

    number = candidates[0].get("number")
    if type(number) is not int or number < 1:
        raise UnsafeToPublish("Unrecognized pending daily PR number")
    pr = api(f"repos/{REPO}/pulls/{number}")
    head = pr.get("head") or {}
    created_at = pr.get("created_at")
    if not (pr.get("number") == number and pr.get("state") == "open"
            and pr.get("merged") is False
            and (pr.get("user") or {}).get("login") == BOT
            and re.fullmatch(r"automation/daily-events/[0-9]+-[0-9]+",
                             str(head.get("ref", "")))
            and (head.get("repo") or {}).get("full_name") == REPO
            and (pr.get("base") or {}).get("ref") == "main"):
        raise UnsafeToPublish("Pending daily PR is not a verified App-owned update")
    try:
        created = datetime.fromisoformat(created_at.replace("Z", "+00:00"))
        if created.tzinfo is None:
            raise ValueError("missing timezone")
    except (AttributeError, TypeError, ValueError) as exc:
        raise UnsafeToPublish("Pending daily PR has invalid creation time") from exc
    if datetime.now(timezone.utc) - created < timedelta(hours=2):
        raise UnsafeToPublish("A recent daily PR may still be active")
    if current_main() != base_sha:
        raise UnsafeToPublish("main changed during stale PR cleanup")

    result = api(f"repos/{REPO}/pulls/{number}", method="PATCH",
                 fields=("state=closed",))
    if result.get("number") != number or result.get("state") != "closed":
        raise UnsafeToPublish("GitHub did not confirm stale PR closure")
    summary = os.environ.get("GITHUB_STEP_SUMMARY", "")
    if summary:
        with Path(summary).open("a", encoding="utf-8") as handle:
            handle.write(
                f"Closed stale App-owned daily PR #{number} before a fresh update.\n")
    print(f"Closed stale daily event PR #{number}; a new verified update may proceed.")



def verify_merged_payload(merged_sha):
    """Check the actual squash commit contains the vetted event bytes.

    Compare GitHub's immutable commit-content endpoint with locally validated
    files; do not depend on cache state or assume a successful merge result
    necessarily published the expected JSON.
    """
    if not re.fullmatch(r"[0-9a-f]{40}", merged_sha):
        raise UnsafeToPublish("Invalid merged commit identifier")
    for path in sorted(ALLOWED):
        remote = api(
            f"repos/{REPO}/contents/{path}?ref={merged_sha}")
        if (remote.get("type") != "file"
                or remote.get("encoding") != "base64"
                or not isinstance(remote.get("content"), str)):
            raise UnsafeToPublish(
                f"Verified event payload not readable at merged SHA: {path}")
        try:
            decoded = base64.b64decode(
                "".join(remote["content"].split()), validate=True)
        except (ValueError, binascii.Error) as exc:
            raise UnsafeToPublish(
                f"Invalid merged event-data encoding: {path}") from exc
        if decoded != Path(path).read_bytes():
            raise UnsafeToPublish(
                f"Merged event-data differs from validated local file: {path}")


def verify_merged_commit_parent(original_main_sha, merged_sha):
    """Detect a main race across REST merge: the REST sha guard protects HEAD only.

    The squash commit must directly descend from the main SHA that our
    validated event data was generated against. This is POST-merge detection,
    not a transactional pre-merge guarantee.
    """
    if not (re.fullmatch(r"[0-9a-f]{40}", original_main_sha)
            and re.fullmatch(r"[0-9a-f]{40}", merged_sha)):
        raise UnsafeToPublish("Invalid main or squash commit identifier")
    commit = api(f"repos/{REPO}/git/commits/{merged_sha}")
    parents = commit.get("parents")
    if (not isinstance(parents, list) or len(parents) != 1
            or not isinstance(parents[0], dict)
            or parents[0].get("sha") != original_main_sha):
        raise UnsafeToPublish(
            "main changed across PR merge, or merge commit parent cannot be verified; "
            "inspect published data (already merged)")
    return True


def pages_status(merged_sha):
    """Observe the Pages deployment for the exact merged commit, not any newer run.

    The check runs only after merge. Failure cannot undo a previously merged PR.
    """
    data = api(
        f"repos/{REPO}/actions/runs?head_sha={merged_sha}&per_page=100",
        read_actions=True)
    if not isinstance(data, dict) or not isinstance(data.get("workflow_runs"), list):
        raise UnsafeToPublish("Unable to inspect GitHub Pages deployment runs after merge")
    matches = [
        run for run in data["workflow_runs"]
        if (run.get("head_sha") == merged_sha
            and run.get("head_branch") == "main"
            and run.get("event") == "dynamic"
            and run.get("name") == "pages build and deployment"
            and run.get("path", "").split("@", 1)[0] == PAGES_WORKFLOW
            and (run.get("repository") or {}).get("full_name") == REPO)
    ]
    if len(matches) > 1:
        raise UnsafeToPublish("Ambiguous Pages deployment runs for the merged SHA")
    if not matches:
        return "pending"
    run = matches[0]
    if run.get("status") != "completed":
        return "pending"
    if run.get("conclusion") != "success":
        raise UnsafeToPublish("Pages deployment failed after merge; published content may be stale")
    return "success"


def wait_for_pages(merged_sha):
    deadline = time.monotonic() + PAGES_WAIT_SECONDS
    while True:
        if pages_status(merged_sha) == "success":
            return
        if time.monotonic() >= deadline:
            raise UnsafeToPublish(
                "Pages deployment not confirmed after merge; inspect the live site")
        time.sleep(POLL_SECONDS)


def publish():
    base_sha, branch, number = expected_environment()
    if current_main() != base_sha:
        raise UnsafeToPublish("main changed before validation")
    head_sha = inspect_pr(base_sha, branch, number)
    deadline = time.monotonic() + WAIT_SECONDS
    while True:
        decision = ci_status(branch, head_sha, number)
        if decision == "success":
            break
        if time.monotonic() >= deadline:
            raise UnsafeToPublish("Required PR CI did not finish in time")
        time.sleep(POLL_SECONDS)

    # Recheck GitHub reality after CI; never trust only a prior approval.
    if current_main() != base_sha:
        raise UnsafeToPublish("main moved during PR CI; refusing stale update")
    if inspect_pr(base_sha, branch, number) != head_sha:
        raise UnsafeToPublish("PR head changed after CI")
    if ci_status(branch, head_sha, number) != "success":
        raise UnsafeToPublish("Required CI status changed")

    result = api(f"repos/{REPO}/pulls/{number}/merge", method="PUT",
                 fields=(f"sha={head_sha}", "merge_method=squash"))
    if result.get("merged") is not True:
        raise UnsafeToPublish("GitHub did not accept the tested PR merge")
    merged_sha = result.get("sha", "")
    if not isinstance(merged_sha, str) or not re.fullmatch(r"[0-9a-f]{40}", merged_sha):
        raise UnsafeToPublish("Merge acknowledged but returned an invalid commit SHA")
    # Mark irreversible state immediately. Errors below are POST-MERGE errors:
    # they cannot make an already merged PR unmerged.
    summary = os.environ.get("GITHUB_STEP_SUMMARY", "")
    if summary:
        with Path(summary).open("a", encoding="utf-8") as handle:
            handle.write(
                f"Daily PR #{number} merge acknowledged at {merged_sha}; "
                "post-merge verification pending.\n")
    if current_main() != merged_sha:
        raise UnsafeToPublish("Merged SHA did not match main; inspect publication")
    verify_merged_commit_parent(base_sha, merged_sha)
    verify_merged_payload(merged_sha)
    wait_for_pages(merged_sha)
    if summary:
        with Path(summary).open("a", encoding="utf-8") as handle:
            handle.write(
                f"GitHub Pages deployment succeeded at exact main SHA {merged_sha}. "
                "Live browser/cache freshness was not independently verified.\n")
    print(f"Daily PR #{number} merged; exact-SHA GitHub Pages deployment succeeded.")


if __name__ == "__main__":
    try:
        if sys.argv[1:] == ["--cleanup-stale"]:
            cleanup_stale_daily_prs()
        elif len(sys.argv) == 1:
            publish()
        else:
            raise UnsafeToPublish("Unexpected command arguments")
    except (UnsafeToPublish, KeyError, OSError, subprocess.TimeoutExpired) as exc:
        print(f"Daily publishing or deployment verification failed: {exc}", file=sys.stderr)
        raise SystemExit(1)
