const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const line=html.split('\n').find(s=>s.startsWith('function applyForumEventOverlay('));
assert.ok(line,'Transactional overlay helper must exist');
const manual=fs.readFileSync(path.join(root,'manual-events.js'),'utf8');
const verified=fs.readFileSync(path.join(root,'verified-schedule.js'),'utf8');
assert.ok(manual.includes('window.applyForumEventOverlay(current =>'));
assert.ok(verified.includes('window.applyForumEventOverlay(current =>'));
assert.ok(!manual.includes('EVENTS = merged'));
assert.ok(!verified.includes('EVENTS = merged'));
const original=[{id:'existing',title:'架空の公演'}];
let renders=0;
const ctx={window:{},console,EVENTS:original,refresh(){renders++;}};
vm.createContext(ctx);
vm.runInContext(line+'\nwindow.applyForumEventOverlay=applyForumEventOverlay;',ctx);
const updated=ctx.window.applyForumEventOverlay(current=>current.concat([{id:'new'}]));
assert.equal(updated.length,2);
assert.equal(ctx.EVENTS.length,2);
assert.equal(renders,1);
assert.equal(original.length,1,'Never mutate previously published data');
const prior=ctx.EVENTS;
assert.throws(()=>ctx.window.applyForumEventOverlay(()=>null),/不正/);
assert.equal(ctx.EVENTS,prior);
renders=0;
let fail=true;
ctx.refresh=()=>{renders++;if(fail){fail=false;throw new Error('render failed')}};
assert.throws(()=>ctx.window.applyForumEventOverlay(current=>current.concat([{id:'invalid'}])),/render failed/);
assert.equal(ctx.EVENTS,prior,'A failed render must restore the entire previous array');
assert.equal(renders,2,'On error, re-render the restored array');
assert.equal(prior.length,2);
console.log('PASS: event overlays commit and restore in one centralized transaction');
